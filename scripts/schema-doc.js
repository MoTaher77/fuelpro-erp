'use strict';
/* Print the current database schema as Markdown, built by running every migration on an empty in-memory database.
   Touches no real data. Usage: node scripts/schema-doc.js > docs/DATABASE-SCHEMA.generated.md */
const { openDb } = require('../src/db');
const db = openDb(':memory:');
const q = (sql) => db.prepare(sql).all();
const out = [];
out.push('# Database schema (generated — do not edit by hand)', '',
  `Generated by \`scripts/schema-doc.js\` from the migrations in \`src/db.js\`. PRAGMA user_version = ${db.prepare('PRAGMA user_version').get().user_version}.`,
  'Legend: `*` primary key, `!` NOT NULL, `→` foreign key.', '');
for (const { name } of q("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")) {
  const fk = Object.fromEntries(q(`PRAGMA foreign_key_list(${name})`).map(f => [f.from, f.table]));
  const cols = q(`PRAGMA table_info(${name})`).map(c => `\`${c.name}\` ${c.type || ''}${c.pk ? '*' : ''}${c.notnull ? '!' : ''}${fk[c.name] ? ' →' + fk[c.name] : ''}`);
  const idx = q(`PRAGMA index_list(${name})`).filter(i => !i.name.startsWith('sqlite_autoindex')).map(i => (i.unique ? 'UNIQUE ' : '') + i.name);
  const uq = q(`PRAGMA index_list(${name})`).filter(i => i.name.startsWith('sqlite_autoindex'))
    .map(i => 'UNIQUE(' + q(`PRAGMA index_info(${i.name})`).map(c => c.name).join(', ') + ')');
  out.push(`## ${name}`, cols.join(' · '));
  if (uq.length || idx.length) out.push('', 'Indexes: ' + [...uq, ...idx].join(', '));
  out.push('');
}
out.push('## Triggers', ...q("SELECT name, tbl_name FROM sqlite_master WHERE type='trigger' ORDER BY tbl_name, name").map(t => `- \`${t.name}\` on \`${t.tbl_name}\``), '');
process.stdout.write(out.join('\n'));
