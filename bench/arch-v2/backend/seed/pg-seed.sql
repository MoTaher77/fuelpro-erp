-- Identical data to seed-sqlite.js. N = 1,200,000 sales (2 orgs x 3 stations x 200,000)
DROP TABLE IF EXISTS audit, journal_lines, journals, stock_moves, sales, stations, orgs;
CREATE TABLE orgs(id BIGINT PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE stations(id BIGINT PRIMARY KEY, org_id BIGINT NOT NULL REFERENCES orgs(id), name TEXT NOT NULL);
CREATE TABLE sales(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, station_id BIGINT NOT NULL REFERENCES stations(id), pump_id INTEGER NOT NULL, qty_ml INTEGER NOT NULL, price_e4 INTEGER NOT NULL, amount BIGINT NOT NULL, created_at BIGINT NOT NULL);
CREATE TABLE stock_moves(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, station_id BIGINT NOT NULL, tank_id INTEGER NOT NULL, qty_ml INTEGER NOT NULL, ref_sale BIGINT NOT NULL);
CREATE TABLE journals(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, station_id BIGINT NOT NULL, source TEXT NOT NULL, ref BIGINT NOT NULL);
CREATE TABLE journal_lines(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, journal_id BIGINT NOT NULL REFERENCES journals(id), account_id INTEGER NOT NULL, debit BIGINT NOT NULL DEFAULT 0, credit BIGINT NOT NULL DEFAULT 0);
CREATE TABLE audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id BIGINT NOT NULL, action TEXT NOT NULL, ref BIGINT NOT NULL);
